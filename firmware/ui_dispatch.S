#ifdef XREAL_COMPARE_ONEPRO_WARP
/* BL-site bridge. x16 is the OSD ASLR base supplied by the OSD thunk.
 * All integer registers are restored, except the C dispatcher's x0 result.
 * Native call sites obey AAPCS; q8..q15 preservation follows the C ABI.
 */
.text
.p2align 2
.global xreal_ui_dispatch
.type xreal_ui_dispatch,%function
xreal_ui_dispatch:
    sub sp,sp,#256
    stp x0,x1,[sp,#0]
    stp x2,x3,[sp,#16]
    stp x4,x5,[sp,#32]
    stp x6,x7,[sp,#48]
    stp x8,x9,[sp,#64]
    stp x10,x11,[sp,#80]
    stp x12,x13,[sp,#96]
    stp x14,x15,[sp,#112]
    stp x16,x17,[sp,#128]
    stp x18,x19,[sp,#144]
    stp x20,x21,[sp,#160]
    stp x22,x23,[sp,#176]
    stp x24,x25,[sp,#192]
    stp x26,x27,[sp,#208]
    stp x28,x29,[sp,#224]
    str x30,[sp,#240]
    mov x0,sp
    bl xreal_ui_call
    ldp x0,x1,[sp,#0]
    ldp x2,x3,[sp,#16]
    ldp x4,x5,[sp,#32]
    ldp x6,x7,[sp,#48]
    ldp x8,x9,[sp,#64]
    ldp x10,x11,[sp,#80]
    ldp x12,x13,[sp,#96]
    ldp x14,x15,[sp,#112]
    ldp x16,x17,[sp,#128]
    ldp x18,x19,[sp,#144]
    ldp x20,x21,[sp,#160]
    ldp x22,x23,[sp,#176]
    ldp x24,x25,[sp,#192]
    ldp x26,x27,[sp,#208]
    ldp x28,x29,[sp,#224]
    ldr x30,[sp,#240]
    add sp,sp,#256
    ret
.size xreal_ui_dispatch,.-xreal_ui_dispatch
#endif
.section .note.GNU-stack,"",%progbits
